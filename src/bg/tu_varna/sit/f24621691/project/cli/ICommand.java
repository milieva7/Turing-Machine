package bg.tu_varna.sit.f24621691.project.cli;

/**
 * Общ интерфейс за всички команди в командния интерфейс.
 * Всеки клас, който представлява команда, трябва да реализира метода execute.
 */
public interface ICommand {

    /**
     * Изпълнява конкретната команда с подадените аргументи.
     *
     * @param args аргументите, въведени от потребителя в конзолата
     */
    void execute(String[] args);
}